#: Table holding service agreements (contracts) in the BAZAMS schema.
AGREEMENTS_TABLE = "UMOWACPC"

#: Columns exposed by ``GET /cpc-agreements`` (keys: lower-cased column names).
AGREEMENT_COLUMNS: tuple[str, ...] = (
    "ID_UMOWACPC_TABLE",
    "ID_UMOWACPC",
    "ID_ODDZIAL",
    "ID_KLIENT",
    "ID_ODBIORCA",
    "ID_FIRMA",
    "UMOWA",
    "TYP",
    "HANDLOWIEC",
    "OPIEKUN",
    "OPIEKUNMAIL",
    "OPIEKUNTEL",
    "U_START",
    "U_STOP",
    "WARUNKI",
    "UWAGI",
    "KOSZTY",
    "PRZYCHODY",
    "WYNIK",
    "RABAT",
    "PLATNOSC",
    "TERMIN",
    "AKTYWNA",
    "STRONY_MONO",
    "STRONY_KOLOR",
    "SKANY",
    "FRAEMAIL",
    "PLIK",
)

#: Columns matched by the ``search`` parameter of ``GET /cpc-agreements``.
AGREEMENT_SEARCH_COLUMNS: tuple[str, ...] = (
    "UMOWA",
    "TYP",
    "HANDLOWIEC",
    "OPIEKUN",
    "OPIEKUNMAIL",
    "FRAEMAIL",
    "PLIK",
)

#: Writable agreement details; generated table keys and financial totals stay out.
AGREEMENT_WRITE_COLUMNS: tuple[str, ...] = (
    "ID_KLIENT", "ID_ODDZIAL", "ID_ODBIORCA", "ID_FIRMA",
    "UMOWA", "TYP", "HANDLOWIEC", "OPIEKUN", "OPIEKUNMAIL", "OPIEKUNTEL",
    "U_START", "U_STOP", "WARUNKI", "UWAGI", "RABAT", "PLATNOSC", "TERMIN",
    "AKTYWNA", "STRONY_MONO", "STRONY_KOLOR", "SKANY", "FRAEMAIL", "PLIK",
)

#: Bound the optional machine-link list independently of SQL parameter limits.
MAX_AGREEMENT_MACHINES = 1000

#: Text widths from the connected UMOWACPC catalog, reused by the wire model.
AGREEMENT_TEXT_LENGTHS: dict[str, int] = {
    "UMOWA": 100, "TYP": 100, "HANDLOWIEC": 100, "OPIEKUN": 100,
    "OPIEKUNMAIL": 100, "OPIEKUNTEL": 100, "WARUNKI": 1000, "UWAGI": 1000,
    "PLATNOSC": 250, "AKTYWNA": 20, "FRAEMAIL": 100, "PLIK": 250,
}

#: Defaults matching the legacy agreement with ID_UMOWACPC=1, including its
#: active flag and payment sentinel. The start date is filled with CURRENT_DATE
#: at insertion; record-specific details such as number/type are not copied.
AGREEMENT_INSERT_DEFAULTS: dict[str, Any] = {
    "ID_ODBIORCA": 0, "AUTOCPC": 0, "NOCPCSEND": 0, "AUTOFRA": 0,
    "HANDLOWIEC": "", "OPIEKUN": "", "OPIEKUNMAIL": "", "OPIEKUNTEL": "",
    "WARUNKI": "", "UWAGI": "", "PLIK": "", "FRAEMAIL": "",
    "PLATNOSC": "$_$", "TERMIN": 0, "AKTYWNA": "TAK",
    "IDVAT": 0, "ROZLICZ": 0,
    "UOPLATA1": 0, "UOPLATA2": 0, "UOPLATA3": 0,
    "OPLATA_MONO": 0, "OPLATA_KOLOR": 0, "UOEURO": 0,
    "STRONY_MONO": 0, "STRONY_KOLOR": 0,
    **{f"FRAPAR{i}": 0 for i in range(1, 9)},
    **{f"FRANAZ{i}": "" for i in range(1, 8)},
}


class AgreementsService(BaseDatabaseService):
    """Agreements operations sharing the database service state."""

    def fetch_agreements(
        self,
        *,
        limit: int | None = None,
        offset: int = 0,
        search: str | None = None,
    ) -> dict[str, Any]:
        """Return a page of agreements from the ``UMOWACPC`` table.

        Like :meth:`fetch_clients` this is a hand-picked projection
        (:data:`AGREEMENT_COLUMNS`) of the physical table, so the printing
        parameters (``FRAPAR*``, ``FRANAZ*``/``IDMAG*``) and per-item prices stay
        out of the payload unless the endpoint is extended explicitly.
        """
        page = self._projection_page(
            AGREEMENTS_TABLE,
            AGREEMENT_COLUMNS,
            AGREEMENT_SEARCH_COLUMNS,
            limit=limit,
            offset=offset,
            search=search,
            order_columns=("UMOWA", "ID_UMOWACPC_TABLE"),
            label="agreement",
        )
        page["agreements"] = page.pop("rows")
        return page

    def create_agreement(self, values: Mapping[str, Any]) -> dict[str, Any]:
        """Create an agreement with the lowest unused positive business ID.

        A protected table reservation serialises allocation and insertion across
        connections. The surrogate table key remains generated by the trigger.
        """
        self._require_writes()
        fields, machines = self._agreement_payload(values)
        prepared = self._prepared_write_values(
            fields, AGREEMENT_WRITE_COLUMNS, AGREEMENT_TEXT_LENGTHS
        )
        self._check_client_id(prepared.get("ID_KLIENT"))
        info = self.schema.get(AGREEMENTS_TABLE)
        if not {"ID_UMOWACPC", "ID_KLIENT"} <= info.column_map.keys():
            raise InvalidRequest(
                f"Table '{info.name}' does not contain the required agreement columns"
            )
        key = info.column_map["ID_UMOWACPC"]
        selected = [c for c in AGREEMENT_COLUMNS if c in info.column_map]
        machine_info = self.schema.get(MACHINES_TABLE) if machines is not None else None
        with self.pool.write_session(reserve_table=info.name) as connection:
            cursor = connection.cursor()
            try:
                cursor.execute(build_next_available_id(info.name, key))
                row = cursor.fetchone()
                if row is None or row[0] is None:
                    raise InvalidRequest("No positive agreement identifiers available")
                business_id = int(row[0])
                defaults = dict(AGREEMENT_INSERT_DEFAULTS)
                need_start = "U_START" not in prepared and "U_START" in info.column_map
                need_number = "UMOWA" not in prepared and "UMOWA" in info.column_map
                if need_start or need_number:
                    cursor.execute("SELECT CURRENT_DATE FROM RDB$DATABASE")
                    today = cursor.fetchone()
                    if today is None or today[0] is None:
                        raise DatabaseUnavailable(
                            "Firebird did not return current date"
                        )
                    if need_start:
                        defaults["U_START"] = today[0]
                    if need_number:
                        defaults["UMOWA"] = f"{business_id}/{today[0].year}"
                columns, params = _insert_plan(prepared, defaults, info.column_map)
                statement = build_insert(
                    info.name, [key, *columns], returning=selected
                )
                cursor.execute(statement, [business_id, *params])
                raw_row = cursor.fetchone()
                if raw_row is None:
                    raise DatabaseUnavailable("Firebird did not return the agreement")
                self._link_agreement_machines(
                    cursor, machines, business_id, machine_info
                )
                return self._serialize_row([c.lower() for c in selected], raw_row)
            finally:
                cursor.close()

    def update_agreement(
        self, id_umowacpc: int, values: Mapping[str, Any]
    ) -> dict[str, Any]:
        """Patch an agreement and optionally link machines in one transaction."""
        self._require_writes()
        if (
            not isinstance(id_umowacpc, int)
            or isinstance(id_umowacpc, bool)
            or id_umowacpc < 1
        ):
            raise InvalidRequest("'id_umowacpc' must be a positive integer")
        fields, machines = self._agreement_payload(values)
        prepared = self._prepared_write_values(
            fields, AGREEMENT_WRITE_COLUMNS, AGREEMENT_TEXT_LENGTHS,
            preserve_empty=True,
        )
        if not prepared and machines is None:
            raise InvalidRequest("Supply agreement fields or machines to update")
        if "ID_KLIENT" in prepared:
            self._check_client_id(prepared["ID_KLIENT"])
        info = self.schema.get(AGREEMENTS_TABLE)
        key = info.column_map.get("ID_UMOWACPC")
        if key is None:
            raise InvalidRequest("Agreement table has no ID_UMOWACPC key")
        for column, value in prepared.items():
            if column not in info.column_map:
                raise ColumnNotFound(f"Column '{column}' does not exist")
            if value is None and not next(
                c.nullable for c in info.columns if c.name == info.column_map[column]
            ):
                raise InvalidRequest(f"'{column.lower()}' must not be null")
        selected = [c for c in AGREEMENT_COLUMNS if c in info.column_map]
        machine_info = self.schema.get(MACHINES_TABLE) if machines is not None else None
        projection = ", ".join(quote_identifier(info.column_map[c]) for c in selected)
        with self.pool.write_session(reserve_table=info.name) as connection:
            cursor = connection.cursor()
            try:
                cursor.execute(
                    f"SELECT FIRST 2 {projection} FROM {quote_identifier(info.name)} "
                    f"WHERE {quote_identifier(key)} = ?", [id_umowacpc],
                )
                rows = cursor.fetchall()
                if not rows:
                    raise RecordNotFound(f"Agreement {id_umowacpc} not found")
                if len(rows) > 1:
                    raise RecordConflict(f"Multiple agreements have ID {id_umowacpc}")
                row = rows[0]
                if prepared:
                    statement = build_update(
                        info.name, [info.column_map[c] for c in prepared], key=key,
                        returning=[info.column_map[c] for c in selected],
                    )
                    cursor.execute(statement, [*prepared.values(), id_umowacpc])
                    row = cursor.fetchone()
                    if row is None or all(value is None for value in row):
                        raise RecordNotFound(f"Agreement {id_umowacpc} not found")
                self._link_agreement_machines(
                    cursor, machines, id_umowacpc, machine_info
                )
                return self._serialize_row([c.lower() for c in selected], row)
            finally:
                cursor.close()

    def delete_agreement(self, id_umowacpc: int) -> None:
        """Delete an unreferenced agreement by its unique business identifier."""
        self._require_writes()
        if (
            not isinstance(id_umowacpc, int)
            or isinstance(id_umowacpc, bool)
            or id_umowacpc < 1
        ):
            raise InvalidRequest("'id_umowacpc' must be a positive integer")
        info = self.schema.get(AGREEMENTS_TABLE)
        key = info.column_map.get("ID_UMOWACPC")
        if key is None:
            raise InvalidRequest("Agreement table has no ID_UMOWACPC key")
        references = [
            table for name, table in self.schema.tables().items()
            if name.upper() != AGREEMENTS_TABLE
            and table.kind == "table" and "ID_UMOWACPC" in table.column_map
        ]
        with self.pool.write_session(reserve_table=info.name) as connection:
            cursor = connection.cursor()
            try:
                cursor.execute(
                    f"SELECT FIRST 2 {quote_identifier(key)} "
                    f"FROM {quote_identifier(info.name)} "
                    f"WHERE {quote_identifier(key)} = ?", [id_umowacpc],
                )
                rows = cursor.fetchall()
                if not rows:
                    raise RecordNotFound(f"Agreement {id_umowacpc} not found")
                if len(rows) > 1:
                    raise RecordConflict(f"Multiple agreements have ID {id_umowacpc}")
                # IDs are reused by creation, so dangling links would silently
                # attach historical records to an unrelated new agreement.
                for table in references:
                    column = table.column_map["ID_UMOWACPC"]
                    cursor.execute(
                        f"SELECT FIRST 1 {quote_identifier(column)} "
                        f"FROM {quote_identifier(table.name)} "
                        f"WHERE {quote_identifier(column)} = ?", [id_umowacpc],
                    )
                    if cursor.fetchone() is not None:
                        raise RecordConflict(
                            f"Agreement {id_umowacpc} is referenced by {table.name}"
                        )
                cursor.execute(build_delete(info.name, key=key), [id_umowacpc])
                row = cursor.fetchone()
                if row is None or row[0] is None:
                    raise RecordNotFound(f"Agreement {id_umowacpc} not found")
            finally:
                cursor.close()

    @staticmethod
    def _agreement_payload(
        values: Mapping[str, Any],
    ) -> tuple[dict[str, Any], list[int] | None]:
        """Separate the optional machine list from agreement column values."""
        if not isinstance(values, Mapping):
            raise InvalidRequest("Fields must be a JSON object")
        fields = {}
        machines: list[int] | None = None
        for key, value in values.items():
            if str(key).strip().upper() == "MACHINES":
                if not isinstance(value, list) or len(value) > MAX_AGREEMENT_MACHINES:
                    raise InvalidRequest("'machines' must be a bounded array of IDs")
                if any(
                    not isinstance(item, int) or isinstance(item, bool)
                    or not 1 <= item <= 2147483647 for item in value
                ):
                    raise InvalidRequest("'machines' must contain positive INTEGER IDs")
                machines = list(dict.fromkeys(value))
            else:
                fields[key] = value
        return fields, machines

    def _link_agreement_machines(
        self, cursor: Any, machines: Sequence[int] | None, id_umowacpc: int,
        info: TableInfo | None,
    ) -> None:
        """Replace machine links when supplied; omission preserves existing links."""
        if machines is None:
            return
        required = {"ID_MASZYNA", "ID_MASZYNA_TABLE", "ID_UMOWACPC"}
        if info is None or not required <= info.column_map.keys():
            raise InvalidRequest("Machine table lacks agreement-link columns")
        key = info.column_map["ID_MASZYNA"]
        record_key = info.column_map["ID_MASZYNA_TABLE"]
        agreement_key = info.column_map["ID_UMOWACPC"]
        # Clear only this agreement's links; later validation failures roll this
        # back along with every new assignment and agreement-column change.
        cursor.execute(
            build_update(info.name, [agreement_key], key=agreement_key),
            [None, id_umowacpc],
        )
        find = (
            f"SELECT FIRST 2 {quote_identifier(record_key)} "
            f"FROM {quote_identifier(info.name)} WHERE {quote_identifier(key)} = ?"
        )
        statement = build_update(
            info.name, [agreement_key], key=record_key, returning=[record_key]
        )
        for machine in machines:
            cursor.execute(find, [machine])
            rows = cursor.fetchall()
            if not rows:
                raise RecordNotFound(f"Machine with id_maszyna {machine} not found")
            if len(rows) > 1:
                raise RecordConflict(f"Multiple machines have id_maszyna {machine}")
            cursor.execute(statement, [id_umowacpc, rows[0][0]])
            row = cursor.fetchone()
            if row is None or row[0] is None:
                raise RecordNotFound(f"Machine with id_maszyna {machine} not found")
